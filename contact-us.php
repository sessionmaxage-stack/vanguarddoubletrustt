                e.preventDefault();
                alertBox.style.display = "none";

                const name = document.getElementById("contactName")?.value?.trim() || "";
                const email = document.getElementById("contactEmail")?.value?.trim() || "";
                const phone = document.getElementById("contactPhone")?.value?.trim() || "";
                const subject = document.getElementById("contactSubject")?.value || "General Enquiry";
                const message = document.getElementById("contactMessage")?.value?.trim() || "";

                if (!name) {
                    showAlert("error", "Please enter your full name.");
                    return;
                }

                if (!email || !/^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(email)) {
                    showAlert("error", "Please enter a valid email address.");
                    return;
                }

                if (!message) {
                    showAlert("error", "Please enter your message.");
                    return;
                }

                const originalBtnText = submitBtn ? submitBtn.innerHTML : "Send Message";
                if (submitBtn) {
                    submitBtn.disabled = true;
                    submitBtn.innerHTML = 'Sending Message <i class="fas fa-spinner fa-spin ms-2"></i>';
                }

                try {
                    const response = await fetch("/api/contact", {
                        method: "POST",
                        headers: {
                            "Content-Type": "application/json"
                        },
                        body: JSON.stringify({
                            name: name,
                            email: email,
                            phone: phone,
                            subject: subject,
                            message: message
                        })
                    });

                    const data = await response.json().catch(() => ({}));

                    if (!response.ok) {
                        throw new Error(data.error || "Unable to send your message. Please try again.");
                    }

                    showAlert("success", data.message || "Thank you! Your message has been received. Our team will contact you shortly.");
                    form.reset();
                } catch (err) {
                    showAlert("error", err.message || "Failed to submit message. Please try again.");
                } finally {
                    if (submitBtn) {
                        submitBtn.disabled = false;
                        submitBtn.innerHTML = originalBtnText;
                    }
                }
            });
        });
